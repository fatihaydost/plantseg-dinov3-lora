"""Generates the Kaggle kernel folders: src/*.py is embedded into a single kernel.py (base64 tar); src/ is the only source.
Rerun when the code changes:  python3 build_kernels.py   (then push manually: kaggle kernels push -p <folder>)"""
import base64, io, json, os, tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src')
KAGGLE_USER = 'fatihaydost11'


def package():
    b = io.BytesIO()
    with tarfile.open(fileobj=b, mode='w:gz') as t:
        for f in sorted(os.listdir(SRC)):
            if f.endswith('.py'):
                t.add(os.path.join(SRC, f), arcname=f)
    return base64.b64encode(b.getvalue()).decode()


